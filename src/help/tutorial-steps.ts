import type { TabName } from '../types/tab.js';

/**
 * Контент курса «Обучение» (tutorial_plan.md §3.5). Только данные, без DOM.
 *
 * Порядок шагов — порядок первого запуска, а не порядок вкладок: так каждый шаг
 * отвечает «зачем это сейчас». Цифры правил в тексты не зашиваются — они живут в
 * данных и настройках; описываем механику.
 */

export interface TutorialStep {
  /** Экран, о котором шаг. Нет — шаг общий, вкладка не переключается. */
  tab?: TabName;
  /** Якорь `data-tour` для подсветки блока на экране. */
  anchor?: string;
  title: string;
  /** Абзацы «что и зачем». */
  body: string[];
  /** Практическое мини-задание. Никогда не обязательно — «Далее» не блокируется. */
  practice?: string;
  /** Чеклист выпускного шага. */
  checklist?: string[];
  /** Строка после чеклиста. */
  footer?: string;
}

